import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { BRAND, buildMaterialColumns } from './salesOrderExcel';

function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return [
    parseInt(h.slice(0, 2), 16),
    parseInt(h.slice(2, 4), 16),
    parseInt(h.slice(4, 6), 16),
  ];
}

/**
 * Export bag-order sheet as a landscape PDF (same column layout as on-screen table).
 * @param {Array<{ customerName: string, materialName: string, bags: number }>} entries
 * @param {{ title?: string }} [options]
 */
export function exportBrandedBagBagPdf(entries, options = {}) {
  const { materials, materialMap, maxRows } = buildMaterialColumns(entries);
  if (materials.length === 0) return false;

  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 28;
  const contentWidth = pageWidth - margin * 2;

  const primary = hexToRgb(BRAND.primary);
  const primaryDark = hexToRgb(BRAND.primaryDark);
  const subHeaderBg = hexToRgb(BRAND.subHeaderBg);
  const subHeaderText = hexToRgb(BRAND.subHeaderText);
  const altRow = hexToRgb(BRAND.altRow);
  const border = hexToRgb(BRAND.border);
  const textDark = hexToRgb(BRAND.primaryDark);

  const dateStr = new Date().toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });

  // Brand header bar
  doc.setFillColor(...primaryDark);
  doc.rect(margin, margin, contentWidth, 32, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text(BRAND.companyName, pageWidth / 2, margin + 21, { align: 'center' });

  // Subtitle
  doc.setFillColor(...subHeaderBg);
  doc.rect(margin, margin + 32, contentWidth, 22, 'F');
  doc.setTextColor(...primaryDark);
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(10);
  const parts = [
    options.title || null,
    BRAND.tagline,
    options.filterNote || null,
    dateStr,
  ].filter(Boolean);
  doc.text(parts.join('  ·  '), pageWidth / 2, margin + 46, { align: 'center' });

  const headRow1 = materials.map((mat) => ({
    content: mat,
    colSpan: 2,
    styles: {
      fillColor: primary,
      textColor: 255,
      fontStyle: 'bold',
      halign: 'center',
      valign: 'middle',
    },
  }));

  const headRow2 = materials.flatMap(() => [
    {
      content: 'Name',
      styles: {
        fillColor: subHeaderBg,
        textColor: subHeaderText,
        fontStyle: 'bold',
        halign: 'center',
        fontSize: 8,
      },
    },
    {
      content: 'Qty',
      styles: {
        fillColor: subHeaderBg,
        textColor: subHeaderText,
        fontStyle: 'bold',
        halign: 'center',
        fontSize: 8,
      },
    },
  ]);

  const body = [];
  for (let r = 0; r < maxRows; r++) {
    const row = [];
    for (const mat of materials) {
      const entry = materialMap.get(mat)[r];
      row.push(entry ? entry.customerName : '');
      row.push(entry ? String(entry.bags) : '');
    }
    body.push(row);
  }

  const colCount = materials.length * 2;
  const fontSize = colCount > 14 ? 7 : colCount > 10 ? 8 : 9;

  autoTable(doc, {
    startY: margin + 60,
    margin: { left: margin, right: margin },
    head: [headRow1, headRow2],
    body: body.length ? body : [materials.flatMap(() => ['', ''])],
    theme: 'grid',
    styles: {
      fontSize,
      cellPadding: 4,
      valign: 'middle',
      textColor: textDark,
      lineColor: border,
      lineWidth: 0.4,
      overflow: 'linebreak',
      minCellHeight: 16,
    },
    columnStyles: Object.fromEntries(
      Array.from({ length: colCount }, (_, i) => [
        i,
        {
          halign: i % 2 === 1 ? 'center' : 'left',
          cellWidth: 'auto',
        },
      ])
    ),
    didParseCell: (data) => {
      if (data.section === 'body' && data.row.index % 2 === 1) {
        data.cell.styles.fillColor = altRow;
      }
    },
    tableWidth: 'auto',
  });

  const finalY = doc.lastAutoTable?.finalY || margin + 80;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(127, 154, 136);
  doc.text(
    `Generated by ${BRAND.companyName}  ·  Confidential`,
    pageWidth / 2,
    Math.min(finalY + 18, doc.internal.pageSize.getHeight() - 16),
    { align: 'center' }
  );

  const stamp = new Date().toISOString().slice(0, 10);
  doc.save(`JSR_Bag_Orders_${stamp}.pdf`);
  return true;
}
